"""``hercules completion bash|zsh``: print a shell completion script made from the argument parser itself.

The script completes commands, subcommands (``hercules cloud <TAB>``), options and option values with a fixed set
of choices (``--mode <TAB>``); anything else, such as a case file, falls back to the shell's file completion. It is
generated from the parser, so it never drifts from the real options. zsh uses the same script through
``bashcompinit``.

Install::

    hercules completion bash > ~/.local/share/bash-completion/completions/hercules
    hercules completion zsh > "${fpath[1]}/_hercules"   # or: eval "$(hercules completion zsh)" in ~/.zshrc
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass, field

SHELLS = ("bash", "zsh")


@dataclass
class _Level:
    options: list[str] = field(default_factory=list)
    commands: list[str] = field(default_factory=list)
    choices: dict[str, list[str]] = field(default_factory=dict)


def _levels(parser: argparse.ArgumentParser, path: str = "", found: dict[str, _Level] | None = None) -> dict[str, _Level]:
    levels = {} if found is None else found
    level = levels.setdefault(path, _Level())
    for action in parser._actions:  # noqa: SLF001 - argparse has no public way to walk a parser
        if isinstance(action, argparse._SubParsersAction):  # noqa: SLF001
            for name, child in action.choices.items():
                level.commands.append(name)
                _levels(child, f"{path} {name}".strip(), levels)
            continue
        if action.help == argparse.SUPPRESS or not action.option_strings:
            continue
        level.options.extend(option for option in action.option_strings if option.startswith("--"))
        if action.choices:
            for option in action.option_strings:
                level.choices[option] = [str(choice) for choice in action.choices]
    return levels


def completion_script(parser: argparse.ArgumentParser, shell: str) -> str:
    """The completion script for ``shell`` (bash or zsh)."""
    if shell not in SHELLS:
        raise ValueError(f"unknown shell {shell!r}; use one of {', '.join(SHELLS)}")
    levels = _levels(parser)
    transitions = []
    for path, level in levels.items():
        for command in level.commands:
            child = f"{path} {command}".strip()
            transitions.append(f'      "{path}:{command}") path="{child}" ;;')
    values = []
    for path, level in levels.items():
        for option, choices in level.choices.items():
            values.append(f'    "{path}:{option}") COMPREPLY=($(compgen -W "{" ".join(choices)}" -- "$cur")); return ;;')
    words = []
    for path, level in levels.items():
        words.append(f'    "{path}") commands="{" ".join(level.commands)}"; options="{" ".join(dict.fromkeys(level.options))}" ;;')
    body = "\n".join(
        [
            "# hercules shell completion (generated by `hercules completion`)",
            "_hercules_complete() {",
            '  local cur="${COMP_WORDS[COMP_CWORD]}" prev="${COMP_WORDS[COMP_CWORD-1]}" path="" w i commands="" options=""',
            "  for ((i = 1; i < COMP_CWORD; i++)); do",
            '    w="${COMP_WORDS[i]}"',
            '    case "$path:$w" in',
            *transitions,
            "    esac",
            "  done",
            '  case "$path:$prev" in',
            *values,
            "  esac",
            '  case "$path" in',
            *words,
            "  esac",
            '  if [[ "$cur" == -* ]]; then',
            '    COMPREPLY=($(compgen -W "$options" -- "$cur"))',
            '  elif [[ -n "$commands" ]]; then',
            '    COMPREPLY=($(compgen -W "$commands" -- "$cur"))',
            "  fi",
            "}",
            "complete -o default -F _hercules_complete hercules",
            "",
        ]
    )
    if shell == "zsh":
        return "autoload -U +X compinit && compinit -u\nautoload -U +X bashcompinit && bashcompinit\n" + body
    return body
